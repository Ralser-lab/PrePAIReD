import json
import os
import ast
import re

def read_parameters_file(txt_file, path_to_project_directory, module_order):
    """Read parameter file, extract the modules and create a sub folder for every module. 
    Extract parameters per module in a file and convert each parameter in a json file. 

    :param txt_file: Parameter file generated by user with all modules
    :param path_to_project_directory: directory, where the folders shall be generated
    :param module_order: read the config file to get the right order of moduls
    """
    with open(module_order, "r") as mo:  # mo = module order
        for line in mo:
            full_line = [x.strip() for x in line.split(" ")]  # extract full line
            order = [module for module in full_line if module.isupper()]  # keep capitalized entries only
            order = ["".join(c for c in module if re.match(r'^\w+$', c)) for module in order] # Check for alternative to allow for underscore

    with open(txt_file, "r") as pf: # pf = parameter file
        module_parameter_files = []  # parameter file of each module
        for line in pf:
            # skip comments and empty lines
            if (line[0] == "#") | (line[0] == "\n"):
                continue
            if line.startswith("%%%%%%%%%%"):  # check for module start
                split = line.split("%%%%%%%%%%")  # split module line
                first_digit = order.index(split[1]) // 10  # generate a two digits order for the module folders
                if first_digit == 0:
                    current_module = f"{path_to_project_directory}/{first_digit}{order.index(split[1])}_" + split[1]  # path for the current module
                if first_digit == 1:
                    current_module = f"{path_to_project_directory}/{order.index(split[1])}_" + split[1]  # path for the current module
                os.makedirs(current_module, exist_ok=True)  # generate module directory
                current_parameters_file = open(f"{current_module}/Module_Parameters.txt", "w")  # generate module specific parameter file
                module_parameter_files.append(current_parameters_file)
            else:
                current_parameters_file.write(line)  # add specific parameters

        for module_file in module_parameter_files:  # close all files for now
            module_file.close()
        pf.close()

        # start json conversion and specific folder creation here

        module_folders = os.listdir(path_to_project_directory)  # list of module names
        module_folders = [folder for folder in module_folders if not folder.startswith(".") and re.match(r"^[0-9]", folder[0])]

        for module_folder in module_folders:  # loop over modules to generate the json files
            with open(f"{path_to_project_directory}/{module_folder}/Module_Parameters.txt", "r") as txt_to_json:  # open the module parameter file
                dict1 = {}
                out_file = open(f"{path_to_project_directory}/{module_folder}/Module_Parameters.json", "w")
                
                for line in txt_to_json:
                    splits = line.split("#")  # get rid of comments
                    command, description = splits[0].strip().split("=", 1)  # split between parameter and value
                    description = description.strip()  # remove whitespaces
                    try:
                        description = ast.literal_eval(description)  # check for right dtype
                    except ValueError:
                        pass
                    dict1[command.strip()] = description  # generate dictionary
                json.dump(dict1, out_file, indent=4, sort_keys=False)
                txt_to_json.close()
                out_file.close()

