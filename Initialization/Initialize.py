def update_log(logfile, message):
    log = open(logfile, "a")
    log.write(message+"\n")
    log.close()

def read_dataframe_mdg(filepath: str, log: str, column=None):
    """
    Check if filepath exists and read the dataframe header
    :param filepath: str, path to dataframe
    :param log: str, logfile
    :column: str or None, column to be read-in
    :return: column names of the dataframe
    """
    # print(filepath)
    
    if not isinstance(filepath, str):  # check if filepath is str
        update_log(log,f"###ERROR###: {filepath} is not a string.") 
        raise TypeError(f"{filepath} is not a string.")
    elif filepath.endswith(".tsv"):  # read tsv files
        df = pd.read_csv(filepath, sep="\t", usecols=[column])  # read only the first line to save time
    elif filepath.endswith(".parquet"):  # read parquet files
        df = pd.read_parquet(filepath, columns=[column])  
    return list(pd.unique(df[column]))

def read_parameters_file(txt_file=str, path_to_project_directory=str, metadata_file=str, data_file=str, general_filename="00_GENERAL", run_error_check=True, log=str, parameter_directory=str):
    """Read parameter file, extract the modules and create a sub folder for every module. Extract parameters per module in a file and convert each parameter in a json file. Then, single folders for every parameter are generated to store json files individually and one summary folder with all json files
    :param txt_file: str, Parameter file generated by user with all modules
    :param path_to_project_directory: str, directory, where the folders shall be generated
    :param metadata_file: str, metadata file name
    :param data_file: str, data file name
    :param general_filename: str, name of the json file with general information, default: 00_GENERAL
    :param run_error_check: bool, start (TRUE) or ignore (FALSE) error check, default: TRUE, in case of code modification or testing, FALSE id recommended.
    :param parameter_directory: str, name of the parameter repository
    """
    
    os.makedirs(f"{path_to_project_directory}/Parameter_Files", exist_ok=True)  # create parameters folder
    n_modules = 0  # number of modules in the parameter file
    # pf = parameter file
    metadata_columns = []
    with open(txt_file, "r") as pf:
        module_names = []  # list for each module name
        lines = pf.readlines()
        for encoding_line in lines: # get metadata encoding first to read the file
            if encoding_line.startswith("metadata_encoding"):
                _, encoding = encoding_line.split("=", 1)  # split between parameter and value
                metadata_encoding = encoding.strip()  # remove whitespaces
                # print(f"encoding: {metadata_encoding}")
            else:
                pass

        for line in lines:
            # skip comments and empty lines
            if (line[0] == "#") | (line[0] == "\n"):
                continue
            if line.startswith("%%%%%%%%%%"):  # check for module start
                module_name = line.replace("%", "").strip()
                # module_name = re.search("[a-z]+",line).group(0) # regex solution
                n_modules += 1  # module counter
                # split = line.split("%%%%%%%%%%") # split module line
                params_folder = os.path.join(f"{path_to_project_directory}",parameter_directory)  # path for the current module
                # os.makedirs(current_module, exist_ok=True)  # generate module directory
                current_parameters_file = \
                    open(f"{params_folder}/{module_name}_Parameters.txt", "w") # generate module specific parameter file
                module_names.append(module_name)
            else:
                current_parameters_file.write(line)  # add specific parameters
                if not metadata_file:
                    if line.split("=", 1)[0].strip() in ["metadata_filename_column","metadata_sample_column"]:
                        metadata_columns.append(line.split("=", 1)[1].strip())
                    if line.split("=", 1)[0].strip() in ["input_filename_column"]:
                        input_filename_column_mdg = line.split("=", 1)[1].strip()

        current_parameters_file.close()
        
    # Generate metadata if not available
    if not metadata_file:
        metadata_columns = list(set(metadata_columns))
        samples = read_dataframe_mdg(data_file, log=log, column=input_filename_column_mdg)
        mdg_df = pd.DataFrame(index=metadata_columns,data=[samples]*len(metadata_columns)).T
        
        metadata_file = os.path.join(f"{path_to_project_directory}","Metadata_generated.tsv")
        mdg_df.to_csv(metadata_file, sep="\t", index=False)
        update_log(log, f"No metadata found. Artificial metadata created in {metadata_file}")
        
    # start json conversion and specific folder creation here
    modules = [module for module in module_names if
                      not module.startswith(".") and re.match(r"^[0-9]", module[0])] # check for order and numbers
    # print(module_folders)
    dict_all_parameters = {} # dict where all parameters are stored for error check
    parameters_list = [] # list of parameters with a flag dependency to check for completeness
    for module in modules:  # loop over modules to generate the json files
        if run_error_check:
            update_log(log, f"Start Error check for {module}.")
        # print(module_folder)
        with open(f"{params_folder}/{module}_Parameters.txt", "r") as txt_to_json:# open the module parameter file
            #flag_var = None
            #flag_value_var = None
            if module == general_filename:  # create the general file as starting file for other modules
                dict1 = {}
                flag_var = None
                flag_value_var = None

                with open(f"{params_folder}/{module}_Parameters.json", "w") as out_file:
                    for line in txt_to_json:
                        # print(line)
                        #splits = line.split("#")  # get rid of comments
                        # print(splits)
                        command, description = line.split("=", 1)  # split between parameter and value
                        description = description.strip()  # remove whitespaces
                        command = command.strip()
                        try:  # make strings exceptions readable
                            if description == "TRUE":
                                description = 1
                            if description == "FALSE":
                                description = 0
                            if description == "nan" or description == "Nan" or description == "NaN" or description == "NULL" or description == "None" or description == "none":
                                description = None
                            description = ast.literal_eval(description)  # check for right dtype
                        except:
                            pass
                        dict1[command.strip()] = description  # generate dictionary
                        dict_all_parameters[command.strip()] = description
                        ## ERROR CHECK HERE FOR GENERAL FILE HERE##
                        if run_error_check:
                            module_name = module[3:]
                            #print(f"Start Error check for {module_name}.")
                            flag_var, flag_value_var, parameters_list = error_check.error_check(value=description, variable=command, module=module_name, flag_dictionary=flags_dict, operation_dictionary=operation_dict, current_flag=flag_var, current_flag_value=flag_value_var, user_dict=dict_all_parameters, metadata_file=metadata_file, data_file=data_file, log=log, parameters_list=parameters_list, metadata_encoding=metadata_encoding)
                    # print(dict1)
                    json.dump(dict1, out_file, indent=4, sort_keys=False)  # write to module

            else:  # run the same code for other modules, but read the general module as dict to append it
                with open(f"{params_folder}/{general_filename}_Parameters.json", "r") as general_file:
                    dict1 = json.load(general_file)
                with open(f"{params_folder}/{module}_Parameters.json", "w") as out_file:
                    for line in txt_to_json:
                        # print(line)
                        #splits = line.split("#")  # get rid of comments
                        # print(splits)
                        command, description = line.split("=", 1)  # split between parameter and value
                        description = description.strip()  # remove whitespaces
                        command = command.strip()
                        try:  # make strings exceptions readable
                            if description == "TRUE":
                                description = 1
                            if description == "FALSE":
                                description = 0
                            if description == "nan" or description == "Nan" or description == "NaN" or description == "NULL" or description == "None" or description == "none":
                                description = None
                            description = ast.literal_eval(description)  # check for right dtype
                        except:
                            pass
                        dict1[command.strip()] = description  # generate dictionary
                        dict_all_parameters[command.strip()] = description

                        ## ERROR CHECK HERE FOR MODULES HERE##
                        if run_error_check:
                            try:
                                module_name = module[3:]
                                #print(f"Start Error check for {module_name}.")
                                flag_var, flag_value_var, parameters_list = error_check.error_check(value=description, variable=command, module=module_name, flag_dictionary=flags_dict, operation_dictionary=operation_dict, current_flag=flag_var, current_flag_value=flag_value_var, user_dict=dict_all_parameters, metadata_file=metadata_file, data_file=data_file, log=log, parameters_list=parameters_list, metadata_encoding=metadata_encoding)
                                # print(f"Error check successfully finished for {module_name}.")
                            except Exception as e:
                                #print(e)
                                update_log(log, "###ERROR###: "+str(e))
                                sys.exit(0)
                                # print(dict1)
                    json.dump(dict1, out_file, indent=4, sort_keys=False)  # write to module
        if run_error_check:
            update_log(log,f"Error check successfully finished for {module}.") 

    for file in glob.glob(os.path.join(params_folder, "*.txt")): # remove txt files if wanted
        os.remove(file)
        
