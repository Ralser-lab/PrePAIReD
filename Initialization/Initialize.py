def error_control(parameter_overview_df=pd.DataFrame, metadata_df=pd.DataFrame,
                  user_input_txt=str, diann_df = pd.DataFrame):
    """
    This function checks parameters and values from the user input for right datatype, default
    values and allowed ranges for the called modules.

    :param metadata_df: DataFrame, sample metadata for correction of confounding factors
    :param parameter_overview_df: DataFrame, used as control source for user given values
    :param diann_df: DataFrame, contains the DIA-NN output file, needed for column names
    :param user_input_txt: str, file name of the user chosen parameters to check for errors
    """
    # check all arguments for right type
    if not isinstance(parameter_overview_df, pd.DataFrame): # check if df is really df
       raise TypeError(f"{parameter_overview_df} is not a Dataframe.")
    if not isinstance(metadata_df, pd.DataFrame): # check if df is really df
       raise TypeError(f"{metadata_df} is not a Dataframe.")
    if not isinstance(diann_df, pd.DataFrame): # check if df is really df
       raise TypeError(f"{diann_df} is not a Dataframe.")
    if not isinstance(user_input_txt, str): # check if user input is string
        raise TypeError(f"{user_input_txt} is not a string.")

    # create a df from user input:
    with open(user_input_txt, "r") as ui:
        user_params = pd.DataFrame(columns=["Module", "Parameter", "Value"])
        for line in ui:
            # skip comments and empty lines
            if (line[0] == "#") | (line[0] == "\n"):
                continue
            if line.startswith("%%%%%%%%%%"):  # check for module start
                split_module = line.split("%%%%%%%%%%")
            else:
                 split_param = line.split("=") # split into parameter and value
                 param_value = split_param[1].split("#") # split value if commented
                 # append to df
                 user_params.loc[len(user_params)] = \
                     [split_module[1], split_param[0].strip(), param_value[0].strip()]
        # print(user_params) # check df output

# reduce overview df and user input to current module
    for module in user_params["Module"].unique():
        current_module = parameter_overview_df.loc[parameter_overview_df["Module"] ==
                                                   f"module_{module}"]
        current_user_params = user_params.loc[user_params["Module"] == module]
        # get allowed flag values and check
        allowed_flags = current_module["AllowedValues"].loc[
            (current_module["Function"] == "main") & (current_module["IsFlag"] == 1)].values
        allowed_flags = allowed_flags.split(";")
        if not current_user_params["Value"].isin(allowed_flags).any(): # check if any allowed method was selected by user
            raise ValueError(f"{allowed_flags} not in user defined input for {module}")
        else:
            pass
        used_method = current_user_params["Value"][current_user_params["Value"].isin(allowed_flags)] # check which method was selected

        # get the parameters from overview df for chosen method
        current_method = current_module["Variable", "Type", "Default", "Optional", "AllowedValues"].loc[current_module["Flag_value"] == used_method]
        type_map = {'int': int, 'float': float, 'str': str, 'bool': bool, 'tuple': tuple}
        print(current_method)
        for variable in current_method["Variable"].values: # get right type, range and default
            allowed_type = \
                current_method["Type"].loc[current_method["Variable"] == variable].values[0]
            allowed_values = \
                current_method["AllowedValues"].loc[current_method["Variable"] == variable].values[0]
            default_value = \
                current_method["Default"].loc[current_method["Variable"] == variable].values[0]

            user_value = used_method["Value"].loc[used_method["Parameter"] == variable].values[0] # current user value

            if str(user_value) == default_value: # check via conversion if value is default
                print(f"{user_value} is default value.")
                pass
            else:
                print(f"{user_value} is not a default value, check for allowed values.")
                print(allowed_values, type_map.get(allowed_type))
                # check data type
                if type(user_value) == type_map.get(allowed_type):
                    pass
                else:
                    raise TypeError(f"{user_value} has wrong datatype! "
                                    f"Is {type(user_value)}, should be {type_map.get(allowed_type)}")
                if ";" in allowed_values: # ; indicates list of values, either strings or bools
                    allowed_values = allowed_values.split(";")
                    try: # check for bools
                        allowed_values = [bool(int(x)) for x in allowed_values]
                        if user_value not in allowed_values:
                            raise ValueError(f"{user_value} is not allowed selection!")
                        else:
                            pass
                    except ValueError: # if not bool, check for strings
                        if str(user_value) not in allowed_values:
                            raise ValueError(f"{user_value} is not allowed selection!")
                        else:
                            pass
                    if user_value not in allowed_values:
                        raise ValueError(f"{user_value} is not allowed selection!")
                    else:
                        pass

                # ( indicates a range > first value, [ indicates range >= first value, ) indicates a range < last value, ] indicates range <= last value
                if allowed_values[0] == "(" and allowed_values[-1] == ")":
                    allowed_values = allowed_values[1:-1]
                    # print(allowed_values)
                    allowed_values = allowed_values.split(",")
                    # print(allowed_values)
                    if float(allowed_values[0]) < user_value < float(allowed_values[1]):
                        # print("Value in range.")
                        pass
                    else:
                        raise ValueError(f"{user_value} is not in allowed range, must be > {allowed_values[0]} and < {int(allowed_values[1])}.")
                if allowed_values[0] == "(" and allowed_values[-1] == "]":
                    allowed_values = allowed_values[1:-1]
                    # print(allowed_values)
                    allowed_values = allowed_values.split(",")
                    # print(allowed_values)
                    if float(allowed_values[0]) < user_value <= float(allowed_values[1]):
                        print("Value in range.")
                        pass
                    else:
                        raise ValueError(f"{user_value} is not in allowed range, must be > {allowed_values[0]} and <= {int(allowed_values[1])}.")

                if allowed_values[0] == "[" and allowed_values[-1] == ")":
                    allowed_values = allowed_values[1:-1]
                    # print(allowed_values)
                    allowed_values = allowed_values.split(",")
                    # print(allowed_values)
                    if float(allowed_values[0]) <= user_value < float(allowed_values[1]):
                        # print("Value in range.")
                        pass
                    else:
                        raise ValueError(f"{user_value} is not in allowed range, must be >= {allowed_values[0]} and < {int(allowed_values[1])}.")
                if allowed_values[0] == "[" and allowed_values[-1] == "]":
                    allowed_values = allowed_values[1:-1]
                    # print(allowed_values)
                    allowed_values = allowed_values.split(",")
                    # print(allowed_values)
                    if float(allowed_values[0]) <= user_value <= float(allowed_values[1]):
                        # print("Value in range.")
                        pass
                    else:
                        raise ValueError(f"{user_value} is not in allowed range, must be >= {allowed_values[0]} and <= {int(allowed_values[1])}.")

            # special cases: existence in metadata, check header, check specific length of tuple
            existence_in_md = parameter_overview_df.loc[parameter_overview_df["Operations"] == "existence in metadata"] # identify rows where check is needed
            columns_to_check = existence_in_md["Default"].values
            for column in columns_to_check:
                if column not in metadata_df.columns:
                    raise KeyError(f"{column} not found in metadata!")
                else:
                    pass
            # diann header
            existence_in_diann = parameter_overview_df.loc[parameter_overview_df["Operations"] == "check header"] # identify rows where check is needed
            columns_to_check = existence_in_diann["Default"].values
            for column in columns_to_check:
                if column not in diann_df.columns:
                    raise KeyError(f"{column} not found in metadata!")
                else:
                    pass

